'use strict';

import { generator } from './generator.js';
import { Task } from './task.js';

export async function* asyncGenerator() {
    const suggestions = [
        "Підготуватись до екзамену",
        "Написати конспект лекції",
        "Повторити тему з матаналізу",
        "Прочитати книгу",
        "Зробити лабораторну роботу",
        "Підготувати презентацію",
        "Вивчити нові терміни",
        "Написати реферат",
        "Переглянути лекцію ще раз",
        "Зробити домашнє завдання",
        "Підготуватись до контрольної",
        "Виписати формули",
        "Купити продукти",
        "Прибрати кімнату",
        "Помити посуд",
        "Винести сміття",
        "Записатись до лікаря",
        "Сходити в аптеку",
        "Зробити генеральне прибирання",
        "Організувати робоче місце",
        "Полити квіти",
        "Попрати одяг",
        "Приготувати їжу",
        "Скласти список покупок",
        "Піти в спортзал",
        "Зробити зарядку",
        "Прогулятись",
        "Вивчити 20 нових слів",
        "Подивитись навчальне відео",
        "Попрактикувати англійську",
        "Медитувати 10 хвилин",
        "Розтяжка",
    ];

    let id = 1;
    const gen = generator();

    for (const text of suggestions) {
        await new Promise(r => setTimeout(r, 300));
        yield new Task(
            id++,
            text,
            gen.next().value,
            Math.floor(Math.random() * 3) + 1
        );
    }
}



